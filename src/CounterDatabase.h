#pragma once

#include "Types.h"

#include <filesystem>
#include <map>
#include <set>
#include <string>
#include <unordered_map>
#include <vector>

// What one scan saw, as input for the suggestion ranking.
struct SuggestInput {
    std::map<std::string, int> items;       // enemy item id -> number of enemies owning it
    std::map<std::string, int> heroes;      // hero id -> number of enemies playing it
    std::map<std::string, int> archetypes;  // "weapon" / "spirit" / "vitality" -> number of such builds
    std::set<std::string> owned;            // item ids you already have: never suggested
};

// counters.json: enemy items, enemy build archetypes and enemy heroes, each mapped to the
// items that counter them (generated by tools/build_counters.py).
class CounterDatabase {
public:
    bool load(const std::filesystem::path& file);

    size_t size() const { return items_.size(); }
    size_t heroCount() const { return heroes_.size(); }
    std::set<std::string> heroIds() const;

    // Human-readable names; the id itself when counters.json does not know it.
    std::string displayName(const std::string& itemId) const;
    std::string heroName(const std::string& heroId) const;
    std::string archetypeName(const std::string& slot) const;

    // "weapon" / "spirit" / "vitality", empty if unknown.
    std::string slotOf(const std::string& itemId) const;
    std::string tipFor(const std::string& itemId) const;
    std::vector<std::string> avoidAgainst(const std::string& heroId) const;

    // Score of a counter = sum over what it answers of (count x entry weight x counter priority).
    std::vector<Suggestion> suggest(const SuggestInput& input, size_t maxResults) const;

private:
    struct Counter {
        std::string item;
        std::string reason;
        int priority = 1;  // 3 = first pick, 2 = good, 1 = situational
    };
    struct Entry {
        std::string display;
        int weight = 1;
        std::vector<Counter> counters;
        std::string slot;
        int tier = 0;
        std::string tip;
        std::vector<std::string> avoid;
    };
    using Table = std::unordered_map<std::string, Entry>;

    static std::string nameIn(const Table& table, const std::string& id);

    Table items_;
    Table heroes_;
    Table archetypes_;
    std::unordered_map<std::string, std::string> itemIdByName_;  // counters refer to items by name
};
